import {describe, expect, it} from 'vitest';
import {movementKindOf} from '../movementText';

describe('movementKindOf', () => {
  it('puts every movement text in one of a few kinds', () => {
    const cases: Array<[string, string]> = [
      ['Αποστολή προς αποστείρωση', 'SEND'],
      ['Παραλαβή στην Αποστείρωση', 'RECEIVE'],
      ['Έναρξη καθαρισμού', 'WASH'],
      ['Σύνθεση πλήρης', 'PREP'],
      ['Φόρτωση στον Κλίβανο Ατμού 01', 'CYCLE'],
      ['Κύκλος 2026-0931 ολοκληρώθηκε · αναμονή αποδέσμευσης', 'CYCLE'],
      ['Αποδέσμευση φορτίου 2026-0928', 'RELEASE'],
      ['Ανάκληση φορτίου 2026-0911 · επιστροφή για επαναποστείρωση', 'RELEASE'],
      ['Ηλεκτρονικά προωθημένο · αναμονή φυσικής παράδοσης', 'DELIVERY'],
      ['Παράδοση στο τμήμα · υπογραφή παραλαμβάνοντα', 'DELIVERY'],
      ['Αφαίρεση από σύνθεση · προς Service', 'LOSS'],
      ['Δήλωση απώλειας', 'LOSS'],
      ['Συμπλήρωση ορίου χρήσεων', 'OTHER'],
      ['Ολοκλήρωση ελέγχου · Συσκευασία & Σήμανση', 'PREP'],
      // Every other text the actions write.
      ['Αποδεσμεύτηκε · κύκλος 2026-0931 · Κλίβανος Ατμού 01', 'RELEASE'],
      ['Μη αποδέσμευση · προς επανεπεξεργασία · κύκλος 2026-0931', 'RELEASE'],
      ['Μη αποδέσμευση φορτίου L1 · κύκλος 2026-0931', 'RELEASE'],
      ['ΑΝΑΚΛΗΣΗ R1 · φορτίο L1 · υγρασία', 'RELEASE'],
      ['Κύκλος ολοκληρώθηκε · Κλίβανος Ατμού 01 · 2026-0931 · 134°C', 'CYCLE'],
      ['Αποτυχία κύκλου 2026-0931 · Κλίβανος Ατμού 01', 'CYCLE'],
      ['Βιολογικός δείκτης αρνητικός', 'CYCLE'],
      ['Σύνθεση / προετοιμασία ολοκληρώθηκε · προς κλιβανισμό', 'PREP'],
      ['Παράδοση / παραλαβή ολοκληρώθηκε · παρέδωσε Μαρία · παρέλαβε Νίκος', 'DELIVERY'],
      ['Παράδοση στο τμήμα', 'DELIVERY'],
      ['Επιστροφή στο τμήμα', 'DELIVERY'],
      ['Ηλεκτρονική αποστολή · Άννα (5b39fe1b) · αναμονή φυσικής παραλαβής', 'SEND'],
      ['Αποστολή Σετ σε Service', 'LOSS'],
      ['Απόσυρση · φθορά', 'LOSS'],
      ['Παραλαβή παραγγελίας · νέο εργαλείο στο Απόθεμα', 'OTHER'],
      ['Καταμέτρηση εργαλείων υπογεγραμμένη · 10/11', 'OTHER'],
      // As the load actions write them.
      ['Φορτίο πλυντηρίου L1794482016773-t8wvpx · Πλυντήριο 01 · 2026-0412 · Εργαλεία', 'WASH'],
      ['Φορτίο πλυντηρίου L1794482016773-t8wvpx · Πλυντήριο 01 · 2026-0412 · ΑΠΟΤΥΧΙΑ', 'WASH'],
      ['Φορτίο L1794482016773-t8wvpx · Κλίβανος Ατμού 01 · κύκλος 2026-0931 · σε εξέλιξη', 'CYCLE'],
      ['Φορτίο L1794482016773-t8wvpx · Κλίβανος Ατμού 01 · 2026-0931 · επιτυχές', 'CYCLE'],
      ['Επιστροφή στον κλίβανο · Φορτίο L1 · Κλίβανος Ατμού 01 · 2026-0931 · υγρασία', 'CYCLE'],
    ];
    for (const [text, kind] of cases) expect([text, movementKindOf(text)]).toEqual([text, kind]);
  });
});
